def stage_telemetry(args) -> None:
    stage(3, "Telemetry from the iFogSim devices", "31 simulations (one JVM each): every node reports "
          "every epoch for 100 epochs; failures genuinely stop service.")
    have = all(design.raw_path(s, k).exists() for s, k, _ in design.all_runs())
    if args.full or not have:
        runs = design.all_runs()
        jobs = [("ScenarioSweep", [str(s), str(k), javarun.relpath_from_ifogsim(design.raw_path(s, k)),
                                   str(design.SIM_TIME)]) for s, k, _ in runs]
        with Progress(TextColumn("  [progress.description]{task.description}"), BarColumn(),
                      TextColumn("{task.completed}/{task.total}"), TimeElapsedColumn(),
                      console=console) as prog:
            task = prog.add_task("simulating", total=len(jobs))
            javarun.run_many(jobs, on_done=lambda d, t, r: prog.update(task, completed=d))
    t = Table(box=box.SIMPLE_HEAD, title=None, show_edge=False)
    for col, j in (("Split", "left"), ("Runs", "right"), ("Snapshots", "right"), ("Failed nodes", "right"),
                   ("wear-out", "right"), ("sudden", "right"), ("battery", "right"), ("Positive rows", "right")):
        t.add_column(col, justify=j)
    for split in ("train", "test"):
        frames = [pd.read_csv(design.raw_path(s, k), usecols=["node_name", "failure_time", "failure_cause",
                                                              "ground_truth_fail"])
                  for s, k, sp in design.all_runs() if sp == split]
        n_rows = sum(len(f) for f in frames)
        pos = sum(int(f.ground_truth_fail.sum()) for f in frames)
        causes = pd.concat([f.dropna(subset=["failure_time"]).groupby("node_name").failure_cause.first()
                            for f in frames])
        t.add_row(split, str(len(frames)), f"{n_rows:,}", f"{len(causes):,}", str((causes == "wear-out").sum()),
                  str((causes == "sudden").sum()), str((causes == "battery").sum()), f"{pos:,}")
    console.print(t)



def stage_verdict(args) -> None:
    stage(9, "Verdict: why the BBN")
    comp = json.loads((HERE / "comparison" / "results" / "comparison_summary.json").read_text())
    ft = json.loads((design.RESULTS / "ft" / "summary.json").read_text())
    models = {m["model"]: m for m in comp["models"]}
    bbn = models["BBN (proposed)"]
    learners = [m for n, m in models.items() if n not in ("BBN (elicited, no failure data)", "CPU threshold",
                                                          "Health-index threshold (FTAPA)", "BBN + RF fusion (ablation)")]
    lines: list[Text] = []

    def add(head: str, body: str):
        lines.append(Text.assemble(("  ● ", BLUE), (head, "bold"), ("  " + body, "")))

    best_pr = max(learners, key=lambda m: m["pr_auc"])
    if best_pr["model"] == "BBN (proposed)":
        add("Most accurate on rare failures.", f"PR-AUC {bbn['pr_auc']:.3f}, the highest of "
            f"{len(learners)} trained models (ROC-AUC {bbn['roc_auc']:.3f}).")
    else:
        lo, hi = bbn["pr_auc_ci"]
        blo, bhi = best_pr["pr_auc_ci"]
        tie = hi >= blo and bhi >= lo
        best_roc = max(learners, key=lambda m: m["roc_auc"])
        add("Accuracy." if not tie else "As accurate as the best black box.",
            f"PR-AUC {bbn['pr_auc']:.3f} vs {best_pr['model']} {best_pr['pr_auc']:.3f}"
            + (" (95% intervals overlap)" if tie else "") + f"; ROC-AUC {bbn['roc_auc']:.3f}"
            + (" (best of all models)." if best_roc["model"] == "BBN (proposed)"
               else f" vs best {best_roc['roc_auc']:.3f} ({best_roc['model']})."))
    cal = [m for m in learners if m.get("brier") is not None]
    best_brier = min(cal, key=lambda m: m["brier"])
    best_ece = min(cal, key=lambda m: m["ece"])
    add("Calibrated probabilities." if best_brier["model"] == "BBN (proposed)" else "Calibration.",
        f"Brier {bbn['brier']:.5f}" + (" (best)" if best_brier["model"] == "BBN (proposed)"
                                       else f" vs best {best_brier['brier']:.5f} ({best_brier['model']})")
        + f", ECE {bbn['ece']:.4f}" + (" (best)" if best_ece["model"] == "BBN (proposed)" else "")
        + " -- the controller multiplies P(fail) by a cost, so this matters.")
    lim = comp.get("ceiling") or {}
    if lim:
        add("Close to what is achievable.", f"{lim['sudden']} of the {lim['positives']} held-out failures are "
            f"sudden (no precursor). A predictor clairvoyant about all the others would score ROC-AUC "
            f"{lim['ceiling_roc_auc']:.3f} and PR-AUC {lim['ceiling_pr_auc']:.3f}; the BBN reaches "
            f"{100 * bbn['roc_auc'] / lim['ceiling_roc_auc']:.0f}% and {100 * bbn['pr_auc'] / lim['ceiling_pr_auc']:.0f}%.")
    rob = pd.DataFrame(comp["robustness"])
    skip = ["BBN (elicited, no failure data)", "CPU threshold", "BBN + RF fusion (ablation)"]
    heavy = rob[(rob["mode"] == "mnar") & (rob.rate >= 0.3) & ~rob.model.isin(skip)].groupby("model")
    ll, auc = heavy.log_loss.mean().dropna(), heavy.roc_auc.mean()
    ll_alt = ll.drop("BBN (proposed)")
    body = (f"With 30-60% of channels missing, more often on degrading nodes, the BBN keeps "
            + ("the best" if ll.idxmin() == "BBN (proposed)" else "good")
            + f" probabilities (log-loss {ll['BBN (proposed)']:.4f}; best alternative {ll_alt.min():.4f}, "
            f"{ll_alt.idxmin()}); for ranking, {auc.idxmax()} holds up best (ROC-AUC {auc.max():.3f}"
            + ("" if auc.idxmax() == "BBN (proposed)" else f", BBN {auc['BBN (proposed)']:.3f}")
            + "). Missing channels are summed out, never imputed.")
    add("Missing telemetry.", body)
    el = models["BBN (elicited, no failure data)"]
    prevalence = comp["test_positives"] / comp["test_rows"]
    add("Works before any failure is seen.", f"With only the expert-elicited tables, ROC-AUC {el['roc_auc']:.3f} "
        f"and PR-AUC {el['pr_auc']:.3f} ({el['pr_auc'] / prevalence:.1f}x the chance level {prevalence:.4f}); "
        "a classifier cannot be trained at all without failure labels.")
    add("Explains every alarm.", "Each P(fail) comes with the latent condition driving it "
        "(computational, network, energy or thermal stress) -- shown live in stage 7.")
    pol, tests, dtests = ft["policies"], ft["tests"], ft.get("degraded_tests", {})

    def change(t: dict) -> str:
        p = t["p_value"]
        return f"{t['mean_change_pct']:+.0f}% (" + ("p < 0.001" if p < 1e-3 else f"p = {p:.3f}") + ")"

    for p, name in (("no-ft", "no fault tolerance"), ("reactive", "reactive checkpointing (Rajab 2021)"),
                    ("threshold", "FTAPA threshold migration (Gupta 2025)")):
        if p in tests:
            standby = (f"; warm standby for {100 * pol['bbn']['standby_ratio']:.1f}% of sessions against "
                       f"{100 * pol[p]['standby_ratio']:.0f}%" if pol[p]["standby_ratio"] > 0 else "")
            add(f"vs {name}:", f"downtime from failures + migrations {change(tests[p]['fault'])}, critical "
                f"patients' downtime {change(tests[p]['critical'])}{standby}.")
    if "ml" in tests:
        t = tests["ml"]["fault"]
        body = f"complete telemetry {change(t)}" + ("" if t["p_value"] < 0.05 else ", not significant")
        if "ml" in dtests:
            d = dtests["ml"]["fault"]
            body += (f"; with 30% of telemetry missing, more often on degrading nodes, {change(d)}"
                     + ("" if d["p_value"] < 0.05 else ", not significant"))
        add("vs the same controller driven by ML:", body + ".")
    if "oracle" in pol and "no-ft" in pol:
        nf, ob, bb = (pol[p]["fault_downtime_per_user"] for p in ("no-ft", "oracle", "bbn"))
        if nf > ob:
            add("Against a perfect predictor:", f"of the failure downtime a perfect predictor removes (no fault "
                f"tolerance {nf:.0f} ms per user, oracle {ob:.0f} ms), the BBN framework removes "
                f"{100 * (nf - bb) / (nf - ob):.0f}% ({bb:.0f} ms).")
    if "cloud-only" in pol:
        add("Cloud-only is not an option for critical patients:", f"least downtime, but loop p95 "
            f"{pol['cloud-only']['loop_delay_p95']:.0f} ms misses the 150 ms deadline on every critical alarm.")
    console.print(Panel(Group(*lines), border_style=BLUE, box=box.ROUNDED, padding=(1, 1),
                        title="[bold]evidence from this project's runs[/]"))
    console.print(f"\n  Reports: [bold]model/comparison/results/model_comparison.md[/], "
                  f"[bold]model/results/ft/policy_comparison.md[/], [bold]model/results/verification_report.md[/]")
    console.print(f"  Block diagram: [bold]details/Project_Block_Diagram.png[/]\n")



def stage(n: int, title: str, subtitle: str = "") -> None:
    console.print()
    console.print(Rule(f"[bold]{n}  {title}[/]", style=BLUE, align="left"))
    if subtitle:
        console.print(f"[{MUTED}]{subtitle}[/]")


def ok(msg: str) -> None:
    console.print(f"  [bold {GREEN}]✓[/] {msg}")


def run(cmd: list[str], cwd: Path = HERE, title: str = "", show_tail: int = 0) -> subprocess.CompletedProcess:
    """Runs a step, showing a spinner; on failure prints the output and stops the demo."""
    with console.status(f"[{MUTED}]{title or ' '.join(cmd[:3])}[/]", spinner="dots"):
        res = subprocess.run(cmd, cwd=cwd, text=True, capture_output=True)
    if res.returncode != 0:
        console.print(res.stdout[-3000:], res.stderr[-3000:], style=RED)
        console.print(f"[bold {RED}]step failed: {' '.join(cmd)}[/]")
        sys.exit(1)
    if show_tail:
        for line in res.stdout.strip().splitlines()[-show_tail:]:
            console.print(f"    [{MUTED}]{line}[/]")
    return res


def pct(v, d=1):
    return "n/a" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{100 * v:.{d}f}%"



def stage_train(args) -> None:
    stage(5, "Training the BBN on the devices' telemetry", "Structure: the paper's Fig. 2 plus validated trend "
          "evidence and device-class conditioning; CPTs learned by MAP-EM (latent stress is never observed).")
    sys.path.insert(0, str(HERE))
    import bbn_model
    import train_bbn
    from bbn_io import save_model
    cfg = train_bbn.load_config()
    st = bbn_model.make_structure(trends=cfg["trends"], class_conditional=cfg["class_conditional"],
                                  class_latent=cfg.get("class_latent", False))
    tree = Tree(f"[bold {BLUE}]node_failure[/]  P(fail within 2 epochs | evidence)   "
                f"[{MUTED}]<- 4 latent conditions + reliability prior[/]")
    for latent in st.latent:
        ev = [p for p in st.parents[latent] if p != st.prior]
        tree.add(f"[bold]{latent}[/]  [{MUTED}]<- {', '.join(ev)}"
                 f"{' (+ device class)' if st.prior in st.parents[latent] else ''}[/]")
    tree.add(f"[bold]reliability_prior[/]  [{MUTED}](device class: cloud / fog / edge)[/]")
    console.print(tree)
    sel = design.MODELS / "bbn_config.json"
    if sel.exists():
        c = json.loads(sel.read_text())
        console.print(f"  [{MUTED}]chosen by internal validation on training scenarios only: "
                      f"{'learned ranked-node' if c.get('family') == 'ranked' else 'free'} latent tables, "
                      f"supervised evidence bins (up to {c.get('states', 3)} per channel"
                      f"{', per device class' if c.get('per_class_cuts') else ''}), Dirichlet concentration "
                      f"{c['concentration']:g}, {c['iterations']} EM iterations "
                      f"(CV PR-AUC {c['cv_pr_auc']:.3f}; paper graph with tertiles 0.041)[/]")
    df = pd.read_csv(design.DATA / "telemetry_train_pool.csv")
    start = time.time()
    with console.status(f"[{MUTED}]choosing supervised bins per device class ...[/]", spinner="dots"):
        cuts = train_bbn.cuts_for(df, cfg)
        st = train_bbn.structure_for(cfg, cuts)
    iters = int(cfg["iterations"])
    with Progress(TextColumn("  EM"), BarColumn(), TextColumn("{task.completed}/{task.total} iterations"),
                  TextColumn("log-likelihood [bold]{task.fields[ll]}[/]"), console=console) as prog:
        task = prog.add_task("em", total=iters, ll="-")
        net, history, meta = train_bbn.fit(
            df, st, cuts, cfg["concentration"], max_iter=iters, tol=1e-12, lam=float(cfg.get("lam", 0.05)),
            callback=lambda it, ll: prog.update(task, completed=it, ll=f"{ll:+.5f}"))
    meta["config"] = cfg
    # Trained into a separate file: data/bbn_trained.json is the model every saved result
    # was produced with, and retraining from scratch must reproduce it exactly.
    fresh = design.RESULTS / "bbn_retrained_in_demo.json"
    save_model(net, cuts, fresh, meta)
    ok(f"{meta['rows']:,} snapshots -> {meta['patterns']:,} distinct discretised patterns; trained in "
       f"{time.time() - start:.1f} s")
    saved = json.loads((design.DATA / "bbn_trained.json").read_text())
    new = json.loads(fresh.read_text())
    same_graph = saved["parents"] == new["parents"] and saved["states"] == new["states"]
    if same_graph:
        delta = max(float(np.max(np.abs(np.asarray(saved["cpts"][v]) - np.asarray(new["cpts"][v]))))
                    for v in saved["cpts"])
        ok(f"retrained from scratch = data/bbn_trained.json, the model behind every reported result and "
           f"read by the Java controller (largest CPT difference {delta:.1e})")
    else:
        console.print(f"  [bold {ORANGE}]the retrained network differs from data/bbn_trained.json -- "
                      "run train_bbn.py and the experiments again[/]")
    # What the network learned: risk as a function of the latent conditions (fog node).
    import itertools
    t = Table(title="Learned: P(fail within horizon | latent conditions), fog node", box=box.SIMPLE_HEAD,
              show_edge=False, title_style="bold", title_justify="left", min_width=64)
    for col in ("computational", "network", "energy", "thermal", "P(fail)"):
        t.add_column(col, justify="right" if col == "P(fail)" else "left")
    rows = []
    for combo in itertools.product(("low", "high"), repeat=4):
        p = net.cpts[st.target][combo + ("medium",)][1]
        rows.append((p, combo))
    for p, combo in sorted(rows)[::3]:
        t.add_row(*combo, f"{p:.3f}")
    console.print(t)



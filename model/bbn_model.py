"""
The Bayesian Belief Network over fog-node condition.

The structure is taken from Section III.B of the Review 2 paper. The paper's graph
(Fig. 2) has fourteen variables in four tiers:

    evidence (8)   cpu_util, ram_util, queue_depth,
                   uplink_latency, jitter_pktloss, handover_rate,
                   residual_energy, temperature
    latent (4)     computational_stress, network_degradation,
                   energy_stress, thermal_stress
    prior (1)      reliability_prior
    target (1)     node_failure

    cpu_util, ram_util, queue_depth            -> computational_stress
    uplink_latency, jitter_pktloss,
                        handover_rate          -> network_degradation
    residual_energy                            -> energy_stress
    temperature                                -> thermal_stress
    the four latent nodes + reliability_prior  -> node_failure

That graph is :data:`PAPER`. The model trained for the project may extend it, but only
in two ways that keep its design intact, and only when internal validation shows the
extension helps (``select_bbn.py``):

* **Trend evidence.** A node that is degrading shows it as drift before it shows it as
  an extreme value -- the Review 1 defence brief already promises "trend-derived
  evidence -- rate of change, queue growth". Each trend channel joins the evidence tier
  and feeds the latent condition it belongs to (CPU and queue trend into computational
  stress, latency trend into network degradation, energy drain into energy stress,
  temperature trend into thermal stress). The latent tier and the target are unchanged.
* **Class-conditional evidence.** The reliability prior (device class) becomes a parent
  of each evidence variable, so a channel that does not report is marginalised against
  the distribution typical of that kind of device rather than of the whole fleet.
* **Class-specific latent conditions.** The reliability prior also becomes a parent of
  each latent condition, because the same reading means different things on different
  hardware: an energy drain that is normal for a battery handset is alarming for a
  mains-powered gateway.
* **Finer evidence.** Evidence channels may carry more than three ordered states
  (supervised bins, see ``discretise.py``). The latent conditions and the target keep
  the paper's state spaces -- {low, medium, high} and {not_fail, fail} -- and the latent
  tables use the paper's own ranked-node form with learned parameters
  (``ranked_node.py``), so a finer evidence tier does not make the tables explode.

The paper graph keeps {low, medium, high} everywhere except the binary target.

Note on edge direction. The evidence tier points *into* the latent tier, the opposite of
the usual generative arrangement. That is what the paper specifies, and it is a
deliberate choice: it makes each latent node a ranked aggregator of its indicators,
which can be elicited without failure data. Marginalisation over missing evidence still
works exactly as Eq. (1) requires.

CPTs are not hand-written; they are generated by the ranked-node method from a handful
of elicited weights (``cpt_tables.py``) and then refined from data (``train_bbn.py``).
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field

# Ordinal state space of the paper's variables.
ORDINAL_STATES = ("low", "medium", "high")
TARGET_STATES = ("not_fail", "fail")


def ordinal_states(n: int) -> tuple[str, ...]:
    """Names of an n-state ordinal variable: the paper's names for n = 3, else b1..bn
    (bins in increasing order of the measured value)."""
    if n == 3:
        return ORDINAL_STATES
    return tuple(f"b{i + 1}" for i in range(n))

PRIOR_VAR = "reliability_prior"
TARGET_VAR = "node_failure"

EVIDENCE_VARS = (
    "cpu_util",
    "ram_util",
    "queue_depth",
    "uplink_latency",
    "jitter_pktloss",
    "handover_rate",
    "residual_energy",
    "temperature",
)

TREND_VARS = (
    "cpu_trend",
    "queue_trend",
    "latency_trend",
    "energy_drain",
    "temp_trend",
)

LATENT_VARS = (
    "computational_stress",
    "network_degradation",
    "energy_stress",
    "thermal_stress",
)

#: Which latent condition each evidence channel feeds.
FEEDS = {
    "cpu_util": "computational_stress",
    "ram_util": "computational_stress",
    "queue_depth": "computational_stress",
    "cpu_trend": "computational_stress",
    "queue_trend": "computational_stress",
    "uplink_latency": "network_degradation",
    "jitter_pktloss": "network_degradation",
    "handover_rate": "network_degradation",
    "latency_trend": "network_degradation",
    "residual_energy": "energy_stress",
    "energy_drain": "energy_stress",
    "temperature": "thermal_stress",
    "temp_trend": "thermal_stress",
}

#: Variables that contribute *inversely* to stress and risk. Both keep their natural
#: reading everywhere a human sees them (high residual energy = full battery, high
#: reliability prior = dependable hardware); only their contribution to the child they
#: feed is flipped, in exactly one place: ``cpt_tables.contribution_point``.
INVERTED_VARS = frozenset({"residual_energy", PRIOR_VAR})


@dataclass(frozen=True)
class Structure:
    """A DAG over the fog-node variables."""

    name: str
    evidence: tuple[str, ...]
    latent: tuple[str, ...]
    parents: dict[str, tuple[str, ...]]
    prior: str = PRIOR_VAR
    target: str = TARGET_VAR
    inverted: frozenset[str] = INVERTED_VARS
    #: Number of states of each evidence variable that does not have three.
    state_counts: dict[str, int] = field(default_factory=dict)
    #: "table" (free CPTs, the paper's form) or "ranked" (learned ranked nodes).
    latent_form: str = "table"

    @property
    def variables(self) -> tuple[str, ...]:
        return self.evidence + self.latent + (self.prior, self.target)

    def states(self, var: str) -> tuple[str, ...]:
        if var == self.target:
            return TARGET_STATES
        return ordinal_states(self.state_counts.get(var, 3))

    def card(self, var: str) -> int:
        return len(self.states(var))

    @property
    def class_latent(self) -> bool:
        return any(self.prior in self.parents[l] for l in self.latent)

    def topological_order(self) -> list[str]:
        order: list[str] = []
        seen: set[str] = set()

        def visit(v: str) -> None:
            if v in seen:
                return
            for p in self.parents[v]:
                visit(p)
            seen.add(v)
            order.append(v)

        for v in self.variables:
            visit(v)
        return order

    @property
    def class_conditional(self) -> bool:
        return any(self.parents[e] for e in self.evidence)

    def describe(self) -> str:
        lines = [f"structure {self.name}: {len(self.variables)} variables"]
        for v in self.latent + (self.target,):
            lines.append(f"  {v:22s} <- {', '.join(self.parents[v])}")
        if self.class_conditional:
            lines.append(f"  every evidence variable <- {self.prior}")
        if self.state_counts:
            lines.append("  evidence states: " + ", ".join(f"{v}={self.card(v)}" for v in self.evidence))
        return "\n".join(lines)


def make_structure(trends: bool = False, class_conditional: bool = False,
                   class_latent: bool = False, state_counts: dict[str, int] | None = None,
                   latent_form: str = "table") -> Structure:
    """The paper's graph, optionally extended (see the module docstring)."""
    evidence = EVIDENCE_VARS + (TREND_VARS if trends else ())
    parents: dict[str, tuple[str, ...]] = {}
    for e in evidence:
        parents[e] = (PRIOR_VAR,) if class_conditional else ()
    for latent in LATENT_VARS:
        parents[latent] = tuple(e for e in evidence if FEEDS[e] == latent) + ((PRIOR_VAR,) if class_latent else ())
    parents[PRIOR_VAR] = ()
    parents[TARGET_VAR] = LATENT_VARS + (PRIOR_VAR,)
    name = "paper-fig2"
    if trends:
        name = "fig2+trends"
    if class_conditional:
        name += "+class-evidence"
    if class_latent:
        name += "+class-latent"
    if latent_form == "ranked":
        name += "+ranked"
    counts = {v: n for v, n in (state_counts or {}).items() if v in evidence and n != 3}
    return Structure(name=name, evidence=evidence, latent=LATENT_VARS, parents=parents,
                     state_counts=counts, latent_form=latent_form)


#: The graph exactly as Fig. 2 of the Review 2 paper draws it.
PAPER = make_structure()

# Module-level aliases of the paper graph, kept for readers and existing callers.
ALL_VARS = PAPER.variables
PARENTS = PAPER.parents

#: Never observed on edge devices, which expose no thermal sensor. Present in the
#: network so that it is marginalised out by Eq. (1) rather than imputed.
UNOBSERVABLE_ON_EDGE = frozenset({"temperature", "temp_trend"})


def states_of(var: str) -> tuple[str, ...]:
    """State space of a variable in the paper graph."""
    return TARGET_STATES if var == TARGET_VAR else ORDINAL_STATES


def topological_order() -> list[str]:
    """Topological order of the paper graph."""
    return PAPER.topological_order()


@dataclass
class BayesianNetwork:
    """A discrete Bayesian network: a structure plus one CPT per variable.

    ``cpts[v]`` maps a tuple of parent states (in ``structure.parents[v]`` order) to a
    probability vector over ``structure.states(v)``. Root variables key on ``()``.
    """

    cpts: dict[str, dict[tuple[str, ...], list[float]]] = field(default_factory=dict)
    structure: Structure = PAPER

    @property
    def variables(self) -> tuple[str, ...]:
        return self.structure.variables

    def parents(self, var: str) -> tuple[str, ...]:
        return self.structure.parents[var]

    def states(self, var: str) -> tuple[str, ...]:
        return self.structure.states(var)

    def cpt(self, var: str) -> dict[tuple[str, ...], list[float]]:
        return self.cpts[var]

    def probability(self, var: str, value: str, parent_values: tuple[str, ...]) -> float:
        """P(var = value | parents = parent_values)."""
        row = self.cpts[var][parent_values]
        return row[self.states(var).index(value)]

    def validate(self) -> None:
        """Raises if the network is malformed. Cheap, so callers run it freely."""
        for var in self.variables:
            if var not in self.cpts:
                raise ValueError(f"no CPT for {var}")
            parent_space = [self.states(p) for p in self.parents(var)]
            expected = set(itertools.product(*parent_space)) if parent_space else {()}
            actual = set(self.cpts[var])
            if actual != expected:
                missing = expected - actual
                extra = actual - expected
                raise ValueError(
                    f"CPT for {var} has wrong parent configurations "
                    f"(missing {len(missing)}, unexpected {len(extra)})"
                )
            width = len(self.states(var))
            for config, row in self.cpts[var].items():
                if len(row) != width:
                    raise ValueError(f"CPT row {var}{config} has {len(row)} entries, want {width}")
                if any(p < 0 for p in row):
                    raise ValueError(f"CPT row {var}{config} has a negative probability")
                if abs(sum(row) - 1.0) > 1e-9:
                    raise ValueError(f"CPT row {var}{config} sums to {sum(row)}, want 1")


def build_network(weights=None, structure: Structure = PAPER) -> BayesianNetwork:
    """Builds a network with CPTs generated from the elicited weights.

    ``weights`` optionally supplies complete CPTs (as trained); otherwise the elicited
    ranked-node tables are used.
    """
    from cpt_tables import build_all_cpts

    net = BayesianNetwork(cpts=build_all_cpts(weights, structure), structure=structure)
    net.validate()
    return net
